import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Compiler } from '../dist/index.js';

function adapterReturning(files) {
  return { id: 'claude', emit: () => files };
}

function compilerFor(files) {
  return new Compiler({ claude: adapterReturning(files), cursor: adapterReturning([]), codex: adapterReturning([]), gemini: adapterReturning([]) });
}

const INPUT = { skills: [], catalog: [], agents: [], rules: [], mcpServers: [] };
const OPTS = { provider: 'claude', dryRun: false, force: false };

async function withTempDir(fn) {
  const dir = await mkdtemp(join(tmpdir(), 'aix-compiler-test-'));
  try { await fn(dir); } finally { await rm(dir, { recursive: true, force: true }); }
}

test('compiler writes new emitted files inside the target root', async () => {
  await withTempDir(async (dir) => {
    const c = compilerFor([{ path: 'CLAUDE.md', contents: '# generated by aix\nhello\n' }]);
    const result = await c.compile(INPUT, { ...OPTS, targetRoot: dir });
    assert.deepEqual(result.written, ['CLAUDE.md']);
    assert.equal(await readFile(join(dir, 'CLAUDE.md'), 'utf-8'), '# generated by aix\nhello\n');
  });
});

test('compiler skips files whose content is unchanged', async () => {
  await withTempDir(async (dir) => {
    const file = { path: 'CLAUDE.md', contents: '# generated by aix\nsame\n' };
    const c = compilerFor([file]);
    await c.compile(INPUT, { ...OPTS, targetRoot: dir });
    const second = await c.compile(INPUT, { ...OPTS, targetRoot: dir });
    assert.deepEqual(second.skipped, ['CLAUDE.md']);
    assert.deepEqual(second.written, []);
  });
});

test('compiler refuses to overwrite a user-edited file without force', async () => {
  await withTempDir(async (dir) => {
    await writeFile(join(dir, 'CLAUDE.md'), 'my own handwritten notes\n', 'utf-8');
    const c = compilerFor([{ path: 'CLAUDE.md', contents: '# generated by aix\nnew\n' }]);
    const result = await c.compile(INPUT, { ...OPTS, targetRoot: dir });
    assert.deepEqual(result.conflicts, ['CLAUDE.md']);
    assert.deepEqual(result.written, []);
    assert.equal(await readFile(join(dir, 'CLAUDE.md'), 'utf-8'), 'my own handwritten notes\n');
  });
});

test('compiler overwrites files carrying the generated marker and any file with force', async () => {
  await withTempDir(async (dir) => {
    await writeFile(join(dir, 'CLAUDE.md'), '# generated by aix\nold\n', 'utf-8');
    await writeFile(join(dir, 'USER.md'), 'handwritten\n', 'utf-8');
    const c = compilerFor([
      { path: 'CLAUDE.md', contents: '# generated by aix\nnew\n' },
      { path: 'USER.md', contents: '# generated by aix\nforced\n' },
    ]);
    const result = await c.compile(INPUT, { ...OPTS, targetRoot: dir, force: true });
    assert.deepEqual(result.written.sort(), ['CLAUDE.md', 'USER.md']);
    assert.equal(await readFile(join(dir, 'USER.md'), 'utf-8'), '# generated by aix\nforced\n');
  });
});

test('dry-run reports planned writes without touching the filesystem', async () => {
  await withTempDir(async (dir) => {
    const c = compilerFor([{ path: 'CLAUDE.md', contents: '# generated by aix\nx\n' }]);
    const result = await c.compile(INPUT, { ...OPTS, targetRoot: dir, dryRun: true });
    assert.deepEqual(result.written, ['CLAUDE.md']);
    await assert.rejects(readFile(join(dir, 'CLAUDE.md'), 'utf-8'), /ENOENT/);
  });
});

test('compiler rejects emitted paths that escape the target root', async () => {
  await withTempDir(async (dir) => {
    const c = compilerFor([{ path: '../../escape.md', contents: '# generated by aix\nevil\n' }]);
    await assert.rejects(
      c.compile(INPUT, { ...OPTS, targetRoot: dir }),
      /unsafe path/,
    );
    const absolute = compilerFor([{ path: '/tmp/absolute-escape.md', contents: 'x' }]);
    await assert.rejects(
      absolute.compile(INPUT, { ...OPTS, targetRoot: dir }),
      /unsafe path/,
    );
  });
});
